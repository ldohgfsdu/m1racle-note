import {_electron as electron,expect} from '@playwright/test';
import {mkdtemp,readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {tmpdir} from 'node:os';
import assert from 'node:assert/strict';

const dir=await mkdtemp(join(tmpdir(),'note-foundation-'));
const output=process.env.NOTE_QA_OUTPUT || await mkdtemp(join(tmpdir(),'note-foundation-evidence-'));
await mkdir(output,{recursive:true});
const path=join(dir,'编辑底座.md'),image='![特殊说明](<images/a b.png>)';
const raw=`\ufeff# 编辑底座\r\n\r\n普通段落不能丢失。\n\n${image}\r\n\r\n输入测试。\n\n**跨格式** 和 [链接](https://example.com)。\n`;
await writeFile(path,raw);
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
const entry=process.env.NOTE_TEST_APP_ENTRY || resolve('desktop/main.mjs');
const app=await electron.launch({executablePath:resolve('node_modules/electron/dist/electron.exe'),args:[entry,path,'--user-data-dir='+join(dir,'profile')],env});
try {
 const page=await app.firstWindow(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',event=>{if(event.type()==='error')errors.push(event.text());});
 await page.locator('#filename').filter({hasText:'编辑底座.md'}).waitFor();
 assert.equal(await page.title(),'M1racle Note');
 await expect(page.locator('.cm-content')).toContainText(image);
 assert.equal(await readFile(path,'utf8'),raw);
 const bytes=()=>readFile(path,'utf8');
 await page.locator('.cm-line').filter({hasText:'普通段落'}).click();
 await page.keyboard.press('Home');await page.keyboard.press('Shift+End');
 await page.locator('#format-more summary').click();await page.locator('[data-format=table]').click();
 const template='| 标题 | 标题 |\r\n| --- | --- |\r\n| 内容 | 内容 |';
 const table=raw.replace('普通段落不能丢失。','普通段落不能丢失。\r\n\r\n'+template);
 await expect.poll(bytes).toBe(table);
 await page.keyboard.insertText('项目');
 await expect.poll(bytes).toBe(table.replace('| 标题 |','| 项目 |'));
 await page.locator('#undo').click();await expect.poll(bytes).toBe(table);
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('#redo').click();await expect.poll(bytes).toBe(table);
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('.cm-line').filter({hasText:image}).click();await page.keyboard.press('End');await page.keyboard.insertText('标注');
 await expect.poll(bytes).toBe(raw.replace(image,image+'标注'));
 await page.locator('#code').click();await expect(page.locator('.cm-content')).toContainText(image+'标注');
 await page.locator('#read').click();await expect(page.locator('.cm-content')).toContainText(image+'标注');
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('.cm-line').filter({hasText:'输入测试。'}).click();await page.keyboard.press('Home');
 await page.keyboard.type('abc');await expect.poll(bytes).toBe(raw.replace('输入测试。','abc输入测试。'));
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('#redo').click();await expect.poll(bytes).toBe(raw.replace('输入测试。','abc输入测试。'));
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('.cm-line').filter({hasText:'输入测试。'}).click();await page.keyboard.press('Home');
 const cdp=await page.context().newCDPSession(page);
 await cdp.send('Input.imeSetComposition',{text:'nihao',selectionStart:5,selectionEnd:5});
 await cdp.send('Input.insertText',{text:'你好'});
 await expect.poll(bytes).toBe(raw.replace('输入测试。','你好输入测试。'));
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.locator('.cm-atomic-strong').click();await page.keyboard.press('Home');await page.keyboard.press('Shift+End');
 await page.locator('#selection-menu').waitFor();
 await page.locator('#code').click();await page.locator('#read').click();
 await page.keyboard.insertText('替换整行。');
 await expect.poll(bytes).toBe(raw.replace('**跨格式** 和 [链接](https://example.com)。','替换整行。'));
 await page.locator('#undo').click();await expect.poll(bytes).toBe(raw);
 await page.screenshot({path:join(output,'desktop-foundation.png')});
 await page.setViewportSize({width:720,height:600});await page.locator('#theme').click();
 await page.screenshot({path:join(output,'desktop-foundation-dark-720.png')});
 assert.equal(await page.locator('#error').isVisible(),false);assert.deepEqual(errors,[]);
 assert.equal(await bytes(),raw);
 console.log(JSON.stringify({passed:true,output,checks:['identity-content','unsupported-image-visible-editable','table-insertion-keeps-selection-text','table-header-edit','isolated-undo-redo','grouped-character-typing-undo-redo','mixed-EOL-and-BOM-exact','synthetic-composition-commit-and-undo','cross-format-selection-across-modes','720px-dark','console-clean']}));
} finally {
 await app.evaluate(({app})=>app.exit(0)).catch(()=>{});await app.close().catch(()=>{});
 await rm(dir,{recursive:true,force:true,maxRetries:10,retryDelay:200});
}
